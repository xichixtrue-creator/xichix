"""
Builds Installer.lua: the four Roblox scripts plus the layout Blender exported
(attachment points, pivots, texture names), wrapped in one file you run once in
Roblox Studio.

    python3 build_installer.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT_JSON = os.path.join(HERE, "..", "export", "sword_layout.json")

SOURCES = [
    ("Config", "Config.lua"),
    ("SwordVFX", "SwordVFX.lua"),
    ("Server", "MoFengSwordServer.server.lua"),
    ("Client", "MoFengSwordClient.client.lua"),
]
TEXTURE_KEYS = ["Glow", "Spark", "Star", "Ember", "Smoke", "Flash", "RingSprite", "Wisp", "Beam",
                "Lightning", "Trail", "HiltGold"]
VFX_ASSETS = ["SlashArc", "SlashCore", "ShockRing", "RingCore", "Shard1", "Shard2", "Rock1", "Rock2", "Rock3"]

HEADER = """-- Mo Feng Blade installer (generated by build_installer.py - edit the source files instead).
--
-- 1. Import MoFengSword.fbx and MoFengVFX.fbx (or the .glb files) with the 3D Importer.
-- 2. Run this file once: Model tab > Run Script, or paste it into the Command Bar.
--
-- It builds the "Mo Feng Blade" Tool (StarterPack + a copy in ServerStorage), the
-- VFX assets, and the scripts. Running it again updates the scripts and keeps your Config.
"""


def lua(value, indent=""):
    if isinstance(value, dict):
        inner = indent + "\t"
        items = [f"{inner}{k} = {lua(v, inner)}," for k, v in value.items()]
        return "{\n" + "\n".join(items) + f"\n{indent}}}"
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(value)


def long_string(text):
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def main():
    with open(LAYOUT_JSON) as f:
        layout = json.load(f)
    pts = layout["points"]
    lua_layout = {
        "swordScale": 1.0,
        "points": {k: (v if isinstance(v, list) else float(v)) for k, v in pts.items()},
        "pivots": {k: layout["vfx"][k]["pivotFromCenter"] for k in ("SlashArc", "SlashCore")},
        "textureKeys": TEXTURE_KEYS,
        "vfxAssets": VFX_ASSETS,
    }
    out = [HEADER,
           "-- Change this to resize the sword (and its effects): 0.8 = 20% smaller, 1.2 = 20% bigger.",
           "local SWORD_SCALE = 1.0\n",
           "local SOURCES = {}"]
    for key, filename in SOURCES:
        with open(os.path.join(HERE, filename)) as f:
            out.append(f"SOURCES.{key} = {long_string(f.read())}")
    out.append("local LAYOUT = " + lua(lua_layout).replace("swordScale = 1.0,", "swordScale = SWORD_SCALE,", 1))
    with open(os.path.join(HERE, "Installer.body.lua")) as f:
        body = f.read()
    out.append(re.sub(r"^-- =+\n-- Installer body.*?\n-- =+\n", "", body, flags=re.S))
    path = os.path.join(HERE, "Installer.lua")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {path} ({os.path.getsize(path) // 1024} KB)")


if __name__ == "__main__":
    main()
