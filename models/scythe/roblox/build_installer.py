"""
Builds Installer.lua for the Crimson Reaper scythe: the Roblox scripts, a generated Layout
module (the aura's spiral paths measured in Blender) and the install code, in one file you
run once in Roblox Studio.

    python3 build_installer.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT_JSON = os.path.join(HERE, "..", "export", "scythe_layout.json")

SOURCES = [
    ("Config", "Config.lua"),
    ("ScytheVFX", "ScytheVFX.lua"),
    ("Server", "ScytheServer.server.lua"),
    ("Client", "ScytheClient.client.lua"),
]
TEXTURE_KEYS = ["Ribbon", "SmokeRibbon", "Smoke", "Shard", "Glow", "Spark", "Drip", "Slash", "SlashBand", "Trail",
                "GroundGlow"]

HEADER = """-- Crimson Reaper installer (generated by build_installer.py - edit the source files instead).
--
-- 1. Import Scythe.fbx and ScytheVFX.fbx (or the .glb files) with the 3D Importer.
-- 2. Run this file once: Model tab > Run Script, or paste it into the Command Bar.
--
-- It builds the "Crimson Reaper" Tool (StarterPack + a copy in ServerStorage) and the
-- scripts. Running it again updates the scripts and keeps your Config.
"""


def lua(value, indent=""):
    if isinstance(value, dict):
        inner = indent + "\t"
        items = [f"{inner}{k} = {lua(v, inner)}," for k, v in value.items()]
        return "{\n" + "\n".join(items) + f"\n{indent}}}"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(round(value, 4) if isinstance(value, float) else value)


def long_string(text):
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def blade_spots(layout, count=5):
    """Points along the middle of the blade, root to tip, for the blade's emitters."""
    top, edge = layout["bladeTop"], layout["bladeEdge"]
    n = len(top)
    out = []
    for k in range(count):
        i = round((0.12 + 0.76 * k / (count - 1)) * (n - 1))
        out.append([round((a + b) / 2, 4) for a, b in zip(top[i], edge[i])])
    return out


def main():
    with open(LAYOUT_JSON) as f:
        layout = json.load(f)
    runtime_layout = (
        "-- Generated from the Blender build (scythe_layout.json). Blender coordinates in studs,\n"
        "-- relative to the scythe's origin (the core's height on the shaft axis): { across, depth, up }.\n"
        "return " + lua({"Spirals": layout["spirals"]}) + "\n"
    )
    install_layout = {
        "scytheScale": 1.0,
        "points": layout["points"],
        "bladeSpots": blade_spots(layout),
        "spirals": layout["spirals"],
        "spiralWidths": layout["spiralWidths"],
        "flares": layout["flares"],
        "flareWidths": layout["flareWidths"],
        "textureKeys": TEXTURE_KEYS,
    }
    out = [HEADER,
           "-- Change this to resize the scythe (and its aura): 0.8 = 20% smaller, 1.2 = 20% bigger.",
           "local SCYTHE_SCALE = 1.0",
           "-- How it sits in the hand. GRIP_TILT tips the shaft up from pointing straight ahead",
           "-- (use a negative number if it points at the ground); GRIP_SPIN turns the blade round the shaft.",
           "local GRIP_TILT = 70",
           "local GRIP_SPIN = 0\n",
           "local SOURCES = {}",
           f"SOURCES.Layout = {long_string(runtime_layout)}"]
    for key, filename in SOURCES:
        with open(os.path.join(HERE, filename)) as f:
            out.append(f"SOURCES.{key} = {long_string(f.read())}")
    out.append("local LAYOUT = " + lua(install_layout).replace("scytheScale = 1.0,", "scytheScale = SCYTHE_SCALE,", 1))
    with open(os.path.join(HERE, "Installer.body.lua")) as f:
        body = f.read()
    out.append(re.sub(r"^-- =+\n-- Installer body.*?\n-- =+\n", "", body, flags=re.S))
    path = os.path.join(HERE, "Installer.lua")
    with open(path, "w") as f:
        f.write("\n".join(out))
    with open(os.path.join(HERE, "Layout.lua"), "w") as f:
        f.write(runtime_layout)
    print(f"wrote {path} ({os.path.getsize(path) // 1024} KB)")


if __name__ == "__main__":
    main()
