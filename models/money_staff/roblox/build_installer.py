"""
Builds Installer.lua for the Fortune Staff: the Roblox scripts, a generated Layout module
(the aura's spiral paths measured in Blender) and the install code, in one file you run once
in Roblox Studio.

    python3 build_installer.py
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT_JSON = os.path.join(HERE, "..", "export", "staff_layout.json")

SOURCES = [
    ("Config", "Config.lua"),
    ("StaffVFX", "StaffVFX.lua"),
    ("Server", "StaffServer.server.lua"),
    ("Client", "StaffClient.client.lua"),
]
TEXTURE_KEYS = ["Wisp", "Glow", "Sparkle", "Mote", "Dollar", "Coin", "SlashBand", "Trail", "ShockRing",
                "GroundCircle"]

HEADER = """-- Fortune Staff installer (generated by build_installer.py - edit the source files instead).
--
-- 1. Import MoneyStaff.fbx and MoneyStaffVFX.fbx (or the .glb files) with the 3D Importer.
-- 2. Run this file once: Model tab > Run Script, or paste it into the Command Bar.
--
-- It builds the "Fortune Staff" Tool (StarterPack + a copy in ServerStorage) and the
-- scripts. Running it again updates the scripts and keeps your Config.
"""


def lua(value, indent=""):
    if isinstance(value, dict):
        inner = indent + "\t"
        items = [f"{inner}{k} = {lua(v, inner)}," for k, v in value.items()]
        return "{\n" + "\n".join(items) + f"\n{indent}}}"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(round(value, 4) if isinstance(value, float) else value)


def long_string(text):
    level = 1
    while f"]{'=' * level}]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def main():
    with open(LAYOUT_JSON) as f:
        layout = json.load(f)
    runtime_layout = (
        "-- Generated from the Blender build (staff_layout.json). Blender coordinates in studs,\n"
        "-- relative to the staff's origin (the money symbol's centre): { across, depth, up }.\n"
        "return " + lua({"Spirals": layout["spirals"]}) + "\n"
    )
    install_layout = {
        "staffScale": 1.0,
        "points": layout["points"],
        "ringAxis": layout["ringAxis"],
        "spirals": layout["spirals"],
        "spiralWidths": layout["spiralWidths"],
        "textureKeys": TEXTURE_KEYS,
    }
    out = [HEADER,
           "-- Change this to resize the staff (and its aura): 0.8 = 20% smaller, 1.2 = 20% bigger.",
           "local STAFF_SCALE = 1.0",
           "-- How it sits in the hand. GRIP_TILT tips the shaft up from pointing straight ahead",
           "-- (use a negative number if it points at the ground); GRIP_SPIN turns the money symbol round the shaft.",
           "local GRIP_TILT = 75",
           "local GRIP_SPIN = 0\n",
           "local SOURCES = {}",
           f"SOURCES.Layout = {long_string(runtime_layout)}"]
    for key, filename in SOURCES:
        with open(os.path.join(HERE, filename)) as f:
            out.append(f"SOURCES.{key} = {long_string(f.read())}")
    out.append("local LAYOUT = " + lua(install_layout).replace("staffScale = 1.0,", "staffScale = STAFF_SCALE,", 1))
    with open(os.path.join(HERE, "Installer.body.lua")) as f:
        body = f.read()
    out.append(re.sub(r"^-- =+\n-- Installer body.*?\n-- =+\n", "", body, flags=re.S))
    path = os.path.join(HERE, "Installer.lua")
    with open(path, "w") as f:
        f.write("\n".join(out))
    with open(os.path.join(HERE, "Layout.lua"), "w") as f:
        f.write(runtime_layout)
    print(f"wrote {path} ({os.path.getsize(path) // 1024} KB)")


if __name__ == "__main__":
    main()
